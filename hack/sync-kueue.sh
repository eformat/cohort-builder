#!/usr/bin/env bash
# hack/sync-kueue.sh — sync versioned Kueue API types + operator CRDs from
# openshift/kueue-operator release branches into versioned internal packages.
#
# Sources (read-only `git show` against the local kueue-operator checkout):
#   upstream/release-1.4 -> Kueue operand v0.18.1 -> internal/kueueapi/v0_18_1
#   upstream/release-1.5 -> Kueue operand v0.19.0 -> internal/kueueapi/v0_19_0
# CRDs the operator ships (bindata/assets/kueue-operator/crds) -> internal/crds/<ver>/
#
# Also generates the capability matrix (internal/kueueapi/capabilities.json +
# docs/capabilities.md) by diffing exported struct fields and enum values between
# the two synced packages.
#
# Env:
#   KUEUE_OPERATOR_REPO  path to kueue-operator checkout (default ~/git/kueue-operator)
set -euo pipefail

REPO="${KUEUE_OPERATOR_REPO:-$HOME/git/kueue-operator}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC_API="vendor/sigs.k8s.io/kueue/apis/kueue/v1beta2"
SRC_CRD="bindata/assets/kueue-operator/crds"

if [[ ! -d "$REPO/.git" ]]; then
  echo "error: kueue-operator checkout not found at $REPO (set KUEUE_OPERATOR_REPO)" >&2
  exit 1
fi

# Extract struct fields and enum values from a synced package directory (python,
# TSV on stdout: kind<TAB>key<TAB>value)
extract_surface_py() {
  local dir="$1"
  python3 - "$dir" <<'PY'
import re, sys, pathlib
d = pathlib.Path(sys.argv[1])
field_re = re.compile(r'json:"([^",]+)')
type_re  = re.compile(r'^type ([A-Z][A-Za-z0-9]*) (struct|string)')
enum_re  = re.compile(r'^\t[A-Za-z0-9]+ +[A-Za-z0-9]+ = "([^"]+)"')
field_ln = re.compile(r'^\t[A-Z][A-Za-z0-9]* .+ json:')
for f in sorted(d.glob("*_types.go")):
    cur, kind = None, None
    for line in f.read_text().splitlines():
        m = type_re.match(line)
        if m:
            cur, kind = m.group(1), m.group(2)
            print(f"header\t{kind}\t{cur}")
            continue
        if kind == "struct" and field_ln.match(line):
            m = field_re.search(line)
            if m and m.group(1) != "-":
                print(f"field\t{cur}.{m.group(1)}\t{m.group(1)}")
        elif kind == "string":
            m = enum_re.match(line)
            if m:
                print(f"enum\t{cur}={m.group(1)}\t{m.group(1)}")
        elif line.startswith("}"):
            cur, kind = None, None
PY
}

sync_one() {
  local branch="$1" dir="$2" opver="$3"
  local dst="$ROOT/internal/kueueapi/$dir"
  local crd="$ROOT/internal/crds/$dir"
  mkdir -p "$dst" "$crd"

  echo "==> $branch (kueue operand $opver) -> internal/kueueapi/$dir"
  local files
  files=$(git -C "$REPO" ls-tree --name-only "$branch" -- "$SRC_API/" | sed 's|.*/||' | grep -E '^[a-z_]+_types\.go$|^constants\.go$' || true)
  [[ -n "$files" ]] || { echo "error: no type files found on $branch" >&2; exit 1; }
  for f in $files; do
    # strip scheme-registration init() blocks (they reference SchemeBuilder from
    # groupversion_info.go, which we don't sync — we only marshal, never scheme-encode)
    git -C "$REPO" show "$branch:$SRC_API/$f" \
      | sed "s/^package v1beta2\$/package $dir/" \
      | sed '/^func init() {$/,/^}$/d' > "$dst/$f"
  done

  cat > "$dst/group.go" <<EOF
// Code generated by hack/sync-kueue.sh from kueue-operator ${branch}. DO NOT EDIT.

package ${dir}

// GroupName is the API group for all Kueue resources.
const GroupName = "kueue.x-k8s.io"

// Version is the API version emitted into manifests.
const Version = "v1beta2"

// APIVersion is the fully-qualified groupVersion string.
const APIVersion = GroupName + "/" + Version

// OperandVersion is the sigs.k8s.io/kueue version vendored by the operator branch.
const OperandVersion = "${opver}"
EOF

  echo "==> CRDs -> internal/crds/$dir"
  local crds
  crds=$(git -C "$REPO" ls-tree --name-only "$branch" -- "$SRC_CRD/" | sed 's|.*/||' | grep '\.yaml$' || true)
  for f in $crds; do
    git -C "$REPO" show "$branch:$SRC_CRD/$f" > "$crd/$f"
  done
  echo "    $(ls "$crd" | wc -l) CRDs, $(ls "$dst"/*.go | wc -l) type files"
}

sync_one upstream/release-1.4 v0_18_1 v0.18.1
sync_one upstream/release-1.5 v0_19_0 v0.19.0

echo "==> capability matrix"
python3 "$ROOT/hack/capabilities.py" "$ROOT"

echo "==> done"
