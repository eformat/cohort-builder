#!/usr/bin/env python3
"""hack/capabilities.py — generate the Kueue capability matrix from synced packages.

Usage: capabilities.py <repo-root>
Writes:
  internal/kueueapi/capabilities.json
  docs/capabilities.md
"""
import json
import pathlib
import re
import sys

field_re = re.compile(r'json:"([^",]+)')
type_re = re.compile(r"^type ([A-Z][A-Za-z0-9]*) (struct|string)")
enum_re = re.compile(r'^\t[A-Za-z0-9]+ +[A-Za-z0-9]+ = "([^"]+)"')
field_ln = re.compile(r'^\t[A-Z][A-Za-z0-9]* .+`json:"')  # backtick directly precedes json


def extract(d: pathlib.Path) -> dict:
    fields, enums = set(), {}
    for f in sorted(d.glob("*_types.go")):
        cur, kind = None, None
        for line in f.read_text().splitlines():
            m = type_re.match(line)
            if m:
                cur, kind = m.group(1), m.group(2)
                continue
            if line.startswith("}"):
                cur, kind = None, None
                continue
            if cur is None:
                continue
            if kind == "struct" and field_ln.match(line):
                m = field_re.search(line)
                if m and m.group(1) != "-":
                    fields.add(f"{cur}.{m.group(1)}")
            elif kind == "string":
                m = enum_re.match(line)
                if m:
                    enums.setdefault(cur, set()).add(m.group(1))
    return {"fields": sorted(fields), "enums": {k: sorted(v) for k, v in enums.items()}}


def main() -> None:
    root = pathlib.Path(sys.argv[1])
    versions = ["v0_18_1", "v0_19_0"]
    surf = {v: extract(root / "internal/kueueapi" / v) for v in versions}
    (root / "internal/kueueapi/capabilities.json").write_text(
        json.dumps(surf, indent=2, sort_keys=True) + "\n"
    )

    f14, f15 = set(surf["v0_18_1"]["fields"]), set(surf["v0_19_0"]["fields"])
    lines = [
        "# Kueue capability matrix (generated by hack/sync-kueue.sh; do not edit)",
        "",
        "## Struct fields",
        "",
        "| Field | 1.4 (v0.18.1) | 1.5 (v0.19.0) |",
        "|---|---|---|",
    ]
    for f in sorted(f14 | f15):
        lines.append(f"| `{f}` | {'yes' if f in f14 else '—'} | {'yes' if f in f15 else '—'} |")
    lines += ["", "## Enum value differences", ""]
    diffs = []
    for t in sorted(set(surf["v0_18_1"]["enums"]) | set(surf["v0_19_0"]["enums"])):
        a = set(surf["v0_18_1"]["enums"].get(t, []))
        b = set(surf["v0_19_0"]["enums"].get(t, []))
        if a != b:
            diffs.append((t, sorted(a - b), sorted(b - a)))
    if diffs:
        lines += ["| Enum type | only in 1.4 | only in 1.5 |", "|---|---|---|"]
        for t, a, b in diffs:
            la = ", ".join(f"`{x}`" for x in a) or "—"
            lb = ", ".join(f"`{x}`" for x in b) or "—"
            lines.append(f"| `{t}` | {la} | {lb} |")
    else:
        lines.append("None found.")
    docs = root / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "capabilities.md").write_text("\n".join(lines) + "\n")
    print(
        f"    {len(f15)} fields (1.5) / {len(f14)} (1.4), "
        f"{len(f15 - f14)} only-in-1.5, {len(f14 - f15)} only-in-1.4, {len(diffs)} enum diffs"
    )


if __name__ == "__main__":
    main()
